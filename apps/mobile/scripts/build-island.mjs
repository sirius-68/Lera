// Builds Lera's web screens into one file the native app carries inside it (web/island.js).
// The lesson reader, practice, book import, Ask Lera, the notebook, onboarding and sign-in still run
// from this file, inside the app; the tabs around them are native. See ../README.md.
import { execFileSync } from 'node:child_process';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../..');
execFileSync('node', ['scripts/build.mjs', '--single'], { cwd: root, stdio: 'inherit' });
let html = await readFile(path.join(root, 'dist-single/lera.html'), 'utf8');

// the app's font travels with it, so the screens look the same with no connection
const faces = [['400', '400Regular'], ['500', '500Medium'], ['600', '600SemiBold'], ['700', '700Bold'], ['800', '800ExtraBold']];
let css = '';
for (const [weight, dir] of faces) {
  const ttf = await readFile(path.join(here, `../node_modules/@expo-google-fonts/dm-sans/${dir}/DMSans_${dir}.ttf`));
  css += `@font-face{font-family:'DM Sans';font-style:normal;font-weight:${weight};src:url(data:font/ttf;base64,${ttf.toString('base64')}) format('truetype')}`;
}
html = html.replace(/<link[^>]+fonts\.(googleapis|gstatic)\.com[^>]*>\s*/g, '').replace('</head>', `<style>${css}</style></head>`);
if (!html.includes('<head>')) throw new Error('the page has no <head> to put the host settings in');

await mkdir(path.join(here, '../web'), { recursive: true });
await writeFile(path.join(here, '../web/island.js'), `// Generated by scripts/build-island.mjs. Do not edit.\nmodule.exports = ${JSON.stringify(html)};\n`);
console.log(`island: ${(html.length / 1e6).toFixed(1)} MB`);
