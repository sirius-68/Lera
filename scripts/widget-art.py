#!/usr/bin/env python3
"""Writes the home-screen widget's pictures of Lera as Android vector drawables.

Run from the repo root:  python3 scripts/widget-art.py
The shapes are the same ones src/mascot/Lera.tsx draws; each mood here is a still of that face.
"""
import os

OUT = 'android-overrides/res/drawable'
WHITE, INK, BROW = '#FFFFFFFF', '#FF1B1B1B', '#FF2B2494'


def rrect(x, y, w, h, r):
    return f'M{x + r},{y}h{w - 2 * r}a{r},{r} 0 0 1 {r},{r}v{h - 2 * r}a{r},{r} 0 0 1 -{r},{r}h-{w - 2 * r}a{r},{r} 0 0 1 -{r},-{r}v-{h - 2 * r}a{r},{r} 0 0 1 {r},-{r}z'


def oval(cx, cy, rx, ry=None):
    ry = rx if ry is None else ry
    return f'M{cx - rx},{cy}a{rx},{ry} 0 1 0 {2 * rx},0a{rx},{ry} 0 1 0 -{2 * rx},0z'


def fill(d, color, alpha=None):
    a = f' android:fillAlpha="{alpha}"' if alpha is not None else ''
    return f'<path android:fillColor="{color}"{a} android:pathData="{d}"/>'


def line(d, color, width):
    return f'<path android:strokeColor="{color}" android:strokeWidth="{width}" android:strokeLineCap="round" android:strokeLineJoin="round" android:pathData="{d}"/>'


def spin(inner, deg, px, py, dy=0):
    return f'<group android:rotation="{deg}" android:pivotX="{px}" android:pivotY="{py}" android:translateY="{dy}">{inner}</group>'


HALO = fill(oval(30.6, 40, 43), '#FFFFFFFF', 0.2)  # lifts her off a background close to her own colour
BODY = [
    HALO,
    fill(rrect(0, 0.57, 61.25, 70, 30.62), '#FF6C63FF'),
    line('M9 44c-1.6-9 .8-17 5-22', '#38FFFFFF', 2.6),
    fill('M0.547 33.928C11.12 29.049 32.266 15.105 32.266 0.568 21.693 0.399-0.547 6.584 0.547 33.928Z', '#FF050505'),
    fill('M61.168 35.063C50.601 29.714 29.622 14.768 30.162 0.003 40.916 0.225 63.295 7.332 61.168 35.063Z', '#FF050505'),
]
CHEEKS = [fill(oval(12.6, 53.5, 3.6), '#FFFF9FC0', 0.8), fill(oval(48.6, 53.5, 3.6), '#FFFF9FC0', 0.8)]


def eyes(dx=0.0, dy=0.0, scale=1.0):
    out = []
    for x in (15.31, 32.81):
        out.append(fill(rrect(x, 30.1, 12.03, 20.78, 4.5), WHITE))
        w, h = 6.56 * scale, 8.75 * scale
        px, py = x + 3.28 + dx + (6.56 - w) / 2, 37.76 + dy + (8.75 - h) / 2
        out.append(fill(rrect(round(px, 2), round(py, 2), round(w, 2), round(h, 2), round(w / 2, 2)), INK))
        out.append(fill(oval(round(px + 1.7, 2), round(py + 2.1, 2), 1.05), WHITE))
    return out


ARC = [line('M15.6 43.5q5.7-9.4 11.4 0', WHITE, 3.4), line('M33.1 43.5q5.7-9.4 11.4 0', WHITE, 3.4)]
SHUT = [line('M15.8 41.5q5.5 4.4 11 0', WHITE, 3.4), line('M33.3 41.5q5.5 4.4 11 0', WHITE, 3.4)]
SMILE = [fill('M19.69 57.44C22.79 58.72 31.5 60.51 41.56 57.44 32.38 68.82 23.15 62.18 19.69 57.44Z', WHITE)]
BIG = [fill('M18.3 56.2c6 2.3 19 2.3 24.6 0-1.6 14.6-22.6 14.6-24.6 0Z', WHITE)]
FROWN = [line('M23.6 63q7-5.4 14 0', WHITE, 2.8)]
SMIRK = [line('M24 59.6q7.2 4.6 13.6-1.4', WHITE, 2.8)]


def mouth_o(r=1.0):
    return [fill(oval(30.6, 60.6, round(3.3 * r, 2), round(3.9 * r, 2)), WHITE)]


def brows(left, right, dy=0.0):
    return [spin(line('M16.2 26.4q5-2.2 9.6 0', BROW, 2.2), left, 21, 26, dy), spin(line('M34.4 26.4q5-2.2 9.6 0', BROW, 2.2), right, 39.2, 26, dy)]


SHADES = [
    fill('M10.6 31.4h18.6v8.2a9.3 9.3 0 0 1-18.6 0zM31 31.4h18.6v8.2a9.3 9.3 0 0 1-18.6 0z', '#FF14122E'),
    line('M9 33h42.4', '#FF14122E', 3.2),
    line('M14.6 35.4l5-2.4M35 35.4l5-2.4', '#8CFFFFFF', 1.6),
]
FLAME = [
    fill('M30.6 -17c5.6 5 9.4 8.8 9.4 14.4a9.4 9.4 0 0 1-18.8 0c0-3.4 1.6-5.8 3.4-7.6.4 2.4 1.4 3.6 2.8 4.2-.8-4.2.6-7.8 3.2-11z', '#FFFF8A1F'),
    fill('M30.8 -8.6c2.6 2.4 4.2 4 4.2 6.6a4.4 4.4 0 0 1-8.8 0c0-1.6.8-2.8 1.8-3.6.2 1 .8 1.6 1.4 1.8-.2-1.8.4-3.4 1.4-4.8z', '#FFFFE066'),
]
TEAR = [fill('M21.3 51.5c2.3 3.3 2.5 5.4 0 6.4-2.5-1-2.3-3.1 0-6.4z', '#FF9FD8FF')]
BANG = [line('M62 -6v9', '#FFFF6B5E', 3.2), fill(oval(62, 8.4, 1.9), '#FFFF6B5E')]
# what she dreams: π, a plus and an x, drifting up where the z's would be
DREAM = [
    line('M51 2h8M53 2v6M57 2v5.2q0 1 1.2 0.8', '#FFFFD166', 1.9),
    line('M62 -9h6M65 -12v6', '#FFB8B3FF', 1.9),
    line('M69 -1l4.4 4.4M73.4 -1l-4.4 4.4', '#FF7EE0B0', 1.9),
]
SPARK = [fill('M66 2l1.2 3.2 3.2 1.2-3.2 1.2L66 10.8l-1.2-3.2-3.2-1.2 3.2-1.2z', '#FFFFC940'), fill('M-4 8l1.5 4 4 1.5-4 1.5-1.5 4-1.5-4-4-1.5 4-1.5z', '#FFFFC940')]

MOODS = {
    'happy': BODY + CHEEKS + eyes() + BIG + SPARK,
    'cool': BODY + eyes() + SHADES + SMIRK,
    'fired': BODY + FLAME + CHEEKS + brows(16, -16, 2.2) + eyes(0, 0.4) + BIG,
    'determined': BODY + brows(16, -16, 2.2) + eyes(0, 0.6) + SMIRK,
    'shocked': BODY + brows(0, 0, -3.4) + eyes(0, -0.8, 0.72) + mouth_o(1.3) + BANG,
    'sad': BODY + brows(-18, 18, 1) + eyes(0, 2.4) + TEAR + FROWN,
    'sleepy': BODY + SHUT + mouth_o(0.6) + DREAM,
}

os.makedirs(OUT, exist_ok=True)
for name, parts in MOODS.items():
    body = '\n        '.join(parts)
    xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/widget-art.py. Lera, {name}. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="86dp" android:height="97dp" android:viewportWidth="92" android:viewportHeight="104">
    <group android:translateX="15" android:translateY="22">
        {body}
    </group>
</vector>
'''
    with open(f'{OUT}/widget_lera_{name}.xml', 'w') as f:
        f.write(xml)

BG = {'purple': ('#FF8880FF', '#FF5A51EE'), 'violet': ('#FFA06BFF', '#FF6A3FE0'), 'orange': ('#FFFFB648', '#FFFF7A1A'), 'red': ('#FFFF7A6B', '#FFC52A3F'), 'night': ('#FF34308A', '#FF14123A'), 'ice': ('#FF9DB0CC', '#FF5D6E8C'), 'green': ('#FF4FD89B', '#FF1E9E69')}
for name, (a, b) in BG.items():
    with open(f'{OUT}/widget_bg_{name}.xml', 'w') as f:
        f.write(f'''<?xml version="1.0" encoding="utf-8"?>
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <gradient android:angle="270" android:startColor="{a}" android:endColor="{b}"/>
    <corners android:radius="26dp"/>
</shape>
''')

with open(f'{OUT}/widget_flame.xml', 'w') as f:
    f.write('''<?xml version="1.0" encoding="utf-8"?>
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">
    <path android:fillColor="#FFFFFFFF" android:pathData="M12 2c4.6 4.3 7.8 7.4 7.8 12.2a7.8 7.8 0 0 1-15.6 0c0-2.9 1.3-4.9 2.8-6.4.3 2 1.2 3 2.3 3.5-.6-3.5.5-6.5 2.7-9.3z"/>
    <path android:fillColor="#66FF8A1F" android:pathData="M12.1 11.4c2 1.9 3.3 3.2 3.3 5.2a3.4 3.4 0 0 1-6.8 0c0-1.3.6-2.2 1.4-2.9.2.8.6 1.3 1.1 1.5-.2-1.5.3-2.7 1-3.8z"/>
</vector>
''')
print('wrote', len(MOODS), 'faces,', len(BG), 'backgrounds')
